/**
 * Builds the theme generator into dist/create-theme/.
 *
 * The generator is plain ESM that runs under Node in an app's project, so
 * there is nothing to compile: the files in create-theme/ are copied as they
 * are. The one thing made here is theme-data.js — the default theme the
 * generator checks an app's ramps against:
 *
 *   light / darkOnly   the --color-* and --zabi-* declarations of src/app.css
 *                      (@theme and the .dark rule), unresolved, so the
 *                      generator can re-resolve every role over new ramps
 *   pairs              scripts/contrast-pairs.js — the list check-contrast.js
 *                      holds the library itself to
 *   darkSelectors      scripts/dark-selectors.js — where the dark theme is
 *                      published, for the dark half of a pinned brand
 *
 * It is written on every build from those two sources and is never committed,
 * so it cannot go stale: there is no copy to forget. scripts/verify-build.js
 * fails the build if any of these files is missing, and tests/create-theme
 * .test.js compares the built data with the sources again.
 *
 * Run via `npm run build:create-theme` (part of `npm run build:lib`).
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { readThemeMaps } from './resolve-tokens.js';
import { buildPairs, CONTROL_GRADIENTS } from './contrast-pairs.js';
import { DARK_CLASS, DARK_ATTRIBUTE, AUTO_ATTRIBUTE, AUTO_MEDIA } from './dark-selectors.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const sourceDir = path.join(root, 'create-theme');
const outDir = path.join(root, 'dist', 'create-theme');

/** Everything the published generator consists of, besides theme-data.js. */
export const GENERATOR_FILES = ['index.js', 'index.d.ts', 'cli.js', 'lib/ramp-math.js', 'lib/resolve.js'];
export const THEME_DATA_FILE = 'theme-data.js';

// The control veils' strengths are numbers, not colours, but the veil stops are
// color-mix() of them: without the strengths the generator cannot resolve a
// gradient pair, and would skip it without a word.
const isColourToken = (name) =>
    name.startsWith('--color-') || name.startsWith('--zabi-') || /^--gradient-control-.*-strength$/.test(name);
const pick = (map) => Object.fromEntries(Object.entries(map).filter(([name]) => isColourToken(name)));

/** The default theme as the generator needs it. Pure: same sources, same object. */
export function buildThemeData() {
    const { light, darkOnly } = readThemeMaps(fs.readFileSync(path.join(root, 'src', 'app.css'), 'utf8'));
    return {
        light: pick(light),
        darkOnly: pick(darkOnly),
        pairs: buildPairs(),
        controlGradients: CONTROL_GRADIENTS,
        darkSelectors: { always: `${DARK_CLASS},\n${DARK_ATTRIBUTE}`, auto: AUTO_ATTRIBUTE, media: AUTO_MEDIA },
    };
}

export function renderThemeData(data) {
    return (
        '// Generated by scripts/build-create-theme.js from src/app.css and\n' +
        '// scripts/contrast-pairs.js. Do not edit.\n' +
        `export default ${JSON.stringify(data, null, 2)};\n`
    );
}

function build() {
    fs.rmSync(outDir, { recursive: true, force: true });
    for (const file of GENERATOR_FILES) {
        const target = path.join(outDir, file);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(path.join(sourceDir, file), target);
    }
    fs.chmodSync(path.join(outDir, 'cli.js'), 0o755);

    const data = buildThemeData();
    fs.writeFileSync(path.join(outDir, THEME_DATA_FILE), renderThemeData(data), 'utf8');

    console.log(
        `✓ Built theme generator: ${outDir} ` +
            `(${Object.keys(data.light).length} light tokens, ${Object.keys(data.darkOnly).length} dark, ` +
            `${data.pairs.length} contrast pairs)`,
    );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
