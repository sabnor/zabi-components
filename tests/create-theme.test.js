/**
 * The theme generator, tested as it ships: built into dist/create-theme/ and
 * imported, or run, from there under plain Node. Nothing here reads the
 * generator's source directory, so a file the build forgot to copy fails.
 *
 * Part of `npm run test:themes`, not vitest: the published artefact only
 * exists after a build, and this file makes its own.
 */

const projectRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const distDir = path.join(projectRoot, 'dist', 'create-theme');
const cli = path.join(distDir, 'cli.js');

const built = spawnSync(process.execPath, ['scripts/build-create-theme.js'], { cwd: projectRoot, encoding: 'utf8' });
assert.equal(built.status, 0, `build-create-theme failed:\n${built.stdout}\n${built.stderr}`);

const { createTheme, default: defaultExport, RAMP_STEPS, BASE_STEPS } = await import(
  pathToFileURL(path.join(distDir, 'index.js')).href
);

/** The default theme, straight from the stylesheet (not from the generator's copy). */
const defaults = readThemeMaps(fs.readFileSync(path.join(projectRoot, 'src', 'app.css'), 'utf8'));

/** What a page computes with `tokens` imported after the theme files. */
function themed(tokens) {
  return {
    light: { ...defaults.light, ...tokens },
    dark: { ...defaults.light, ...defaults.darkOnly, ...tokens },
  };
}

const run = (...args) => spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8' });
const contrastWarnings = (result) => result.warnings.filter((w) => w.type === 'contrast');

const BRANDS = ['#0026EA', '#C17B00'];

test('the build puts every generator file in dist, with fresh theme data', () => {
  for (const file of [...GENERATOR_FILES, THEME_DATA_FILE]) {
    assert.ok(fs.existsSync(path.join(distDir, file)), `missing dist/create-theme/${file}`);
  }
  // The generator checks an app's brand against this copy of the default
  // theme. It must be exactly what src/app.css and the pair list say today.
  assert.equal(fs.readFileSync(path.join(distDir, THEME_DATA_FILE), 'utf8'), renderThemeData(buildThemeData()));
  const data = buildThemeData();
  assert.ok(data.pairs.length >= 58, 'the contrast pair list shrank');
  assert.ok(data.pairs.some((pair) => pair.fg === '--color-on-brand'));
  assert.ok(fs.readFileSync(cli, 'utf8').startsWith('#!/usr/bin/env node'));
  assert.ok(fs.statSync(cli).mode & 0o111, 'cli.js is not executable');
});

test('createTheme returns css, tokens, warnings and closest', () => {
  const result = createTheme({ brand: '#0026EA' });
  assert.equal(defaultExport, createTheme);
  assert.deepEqual(Object.keys(result).sort(), ['closest', 'css', 'tokens', 'warnings']);
  assert.equal(typeof result.css, 'string');
  assert.ok(Array.isArray(result.warnings));

  assert.deepEqual(Object.keys(result.tokens), [
    ...RAMP_STEPS.map((step) => `--zabi-brand-${step}`),
    '--zabi-on-brand',
    '--zabi-on-brand-dark',
  ]);
  for (const step of RAMP_STEPS) assert.match(result.tokens[`--zabi-brand-${step}`], /^#[0-9a-f]{6}$/);

  // The css is the tokens, on :root, under a header comment and nothing else.
  const body = /^\/\*[\s\S]*?\*\/\n:root \{\n([\s\S]*)\n\}\n$/.exec(result.css);
  assert.ok(body, 'css is not a header comment followed by one :root rule');
  assert.deepEqual(
    body[1].split('\n'),
    Object.entries(result.tokens).map(([name, value]) => `  ${name}: ${value};`),
  );
  // No accent or neutral was asked for, so the library's own stay in force.
  assert.ok(!result.css.includes('--zabi-accent-'));
  assert.ok(!result.css.includes('--zabi-base-'));
});

