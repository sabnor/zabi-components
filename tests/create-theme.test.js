test('neutral produces all 21 steps on the base scale\'s own lightness, tinted toward the hue', () => {
  const result = createTheme({ brand: '#0026EA', neutral: '#78716c' });
  assert.equal(BASE_STEPS.length, 21);
  for (const half of [75, 150, 250, 350, 450, 550, 650, 750, 850, 925]) assert.ok(BASE_STEPS.includes(half));

  for (const step of BASE_STEPS) {
    const hex = result.tokens[`--zabi-base-${step}`];
    assert.match(hex, /^#[0-9a-f]{6}$/, `--zabi-base-${step}`);
    const expected = measureLightness(defaults.light[`--zabi-base-${step}`]);
    assert.ok(Math.abs(measureLightness(hex) - expected) <= 1, `base-${step} is L* ${measureLightness(hex)}, the base scale has ${expected}`);
    // Warm: red at or above blue, where the default zinc greys lean blue.
    const [r, , b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
    assert.ok(r >= b, `base-${step} ${hex} is not tinted warm`);
  }
  assert.notEqual(result.tokens['--zabi-base-500'], defaults.light['--zabi-base-500']);
  assert.deepEqual(contrastWarnings(result), []);

  // The whole neutral system follows, dark surfaces included.
  const { light, dark } = themed(result.tokens);
  assert.equal(resolveTokenColor(light, '--color-headline'), result.tokens['--zabi-base-900']);
  assert.equal(resolveTokenColor(dark, '--color-surface-base'), result.tokens['--zabi-base-900']);
  assert.notEqual(resolveTokenColor(dark, '--color-surface-raised'), '#262629');

  // A saturated colour as the neutral is only a hue: it stays a grey, and says so.
  const loud = createTheme({ brand: '#0026EA', neutral: '#C17B00' });
  assert.match(loud.warnings.find((w) => w.option === 'neutral').message, /only its hue is used/);
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(loud.tokens['--zabi-base-500'].slice(i, i + 2), 16));
  assert.ok(Math.max(r, g, b) - Math.min(r, g, b) < 40, 'a neutral step came out saturated');
  assert.deepEqual(contrastWarnings(loud), []);
});

